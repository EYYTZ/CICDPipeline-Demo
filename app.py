def add_numbers(a, b):
    """將兩個數字相加"""
    return a + b

def multiply_numbers(a, b):
    """將兩個數字相乘"""
    return a * b

if __name__ == '__main__':
    # 當容器啟動時，會執行這行印出結果
    print("應用程式成功啟動！測試 2 + 3 =", add_numbers(2, 3))